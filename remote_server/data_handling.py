def _section(title, paragraphs):
    """Escape editorial text as well: later copy edits cannot introduce markup."""
    return '<section><h2>' + escape(title, quote=True) + '</h2>' + ''.join(
        '<p>' + escape(text, quote=True) + '</p>' for text in paragraphs
    ) + '</section>'


